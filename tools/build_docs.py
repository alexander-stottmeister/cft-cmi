# A paragraph goes to notation.md when its heading names symbols or conventions;
# everything else defines an object and goes to definitions.md.
NOTATION_KEYWORDS = ("fourier", "hardy", "inner product", "modular frame",
                     "cross-ratio variable", "central charge versus", "constant")

# Project LaTeX macros, expanded so that a plain renderer can typeset the
# formulas.  Each replacement keeps a leading space: the macros are used right
# after other commands ("\\log\\Fid") and must not fuse with them.
TEX_MACROS = [
    (r"\\Fid\b", " F"), (r"\\gB\b", " g_B"), (r"\\gKM\b", " g_{\\mathrm{KM}}"),
    (r"\\cM\b", " \\mathcal{M}"), (r"\\cN\b", " \\mathcal{N}"),
    (r"\\Tr\b", " \\operatorname{Tr}"), (r"\\one\b", " \\mathbf{1}"),
]

TEX_ACCENTS = {r'\"o': "\u00f6", r'\"a': "\u00e4", r'\"u': "\u00fc",
               r'\"O': "\u00d6", r'\"A': "\u00c4", r'\"U': "\u00dc",
               r"\'e": "\u00e9", r"\'a": "\u00e1", r"\`e": "\u00e8",
               r"\ss": "\u00df"}


def tex_to_md(tex: str) -> str:
    tex = re.sub(r"(?m)^\s*%.*$", "", tex)
    for pattern, repl in TEX_MACROS:
        tex = re.sub(pattern, lambda _m, r=repl: r, tex)
    tex = re.sub(r"\\label\{[^}]*\}", "", tex)
    tex = re.sub(r"\\(?:c|C)refrange\{([^}]*)\}\{([^}]*)\}", r"(\1 to \2)", tex)
    tex = re.sub(r"\\(?:c|C)ref\{([^}]*)\}", r"(\1)", tex)
    tex = re.sub(r"\\eqref\{([^}]*)\}", r"(\1)", tex)
    tex = re.sub(r"\\ref\{([^}]*)\}", r"(\1)", tex)
    tex = re.sub(r"\\cite\{([^}]*)\}", r"(\1)", tex)
    tex = re.sub(r"\\emph\{([^}]*)\}", r"*\1*", tex)
    tex = re.sub(r"\\textbf\{([^}]*)\}", r"**\1**", tex)
    tex = re.sub(r"\\begin\{center\}|\\end\{center\}", "", tex)
    tex = re.sub(r"\\begin\{equation\*?\}", "\n$$\n", tex)
    tex = re.sub(r"\\end\{equation\*?\}", "\n$$\n", tex)
    for accent, letter in TEX_ACCENTS.items():
        tex = tex.replace(accent, letter)
    tex = tex.replace("~", " ").replace("\\ ", " ")
    tex = re.sub(r"\\(?=\n)", "", tex)
    tex = re.sub(r"\\[,;!]", " ", tex)
    tex = re.sub(r"[ \t]+\n", "\n", tex)
    tex = re.sub(r"\n{3,}", "\n\n", tex)
    tex = re.sub(r"\$\$\n+", "$$\n", tex)
    tex = re.sub(r"\n+\$\$", "\n$$", tex)
    return tex.strip()


def tabular_to_md(tex: str) -> str:
    m = re.search(r"\\begin\{tabular\}\{[^}]*\}(.*?)\\end\{tabular\}", tex, re.S)
    if not m:
        return tex
    body = m.group(1)
    for rule in ("\\toprule", "\\midrule", "\\bottomrule"):
        body = body.replace(rule, "")
    rows = [r.strip() for r in body.split("\\\\") if r.strip()]
    table = []
    for i, row in enumerate(rows):
        cells = [" ".join(c.split()) for c in row.split("&")]
        table.append("| " + " | ".join(c.replace("|", "\\|") for c in cells) + " |")
        if i == 0:
            table.append("|" + "---|" * len(cells))
    return tex[:m.start()] + "\n" + "\n".join(table) + "\n" + tex[m.end():]


def tex_paragraphs(path: Path):
    text = path.read_text(encoding="utf-8")
    parts = re.split(r"\\paragraph\{([^}]*)\}", text)
    blocks = []
    if parts[0].strip():
        blocks.append(("", parts[0]))
    for i in range(1, len(parts), 2):
        blocks.append((parts[i].strip().rstrip("."), parts[i + 1]))
    return [(title, tex_to_md(tabular_to_md(body))) for title, body in blocks]


def phase6_conventions(path: Path):
    lines = path.read_text(encoding="utf-8").splitlines()
    block, taking = [], False
    for line in lines:
        if line.startswith("## "):
            taking = "convention" in line.lower()
            continue
        if taking:
            block.append(line)
    bullets, current = [], None
    for line in block:
        if line.startswith("- "):
            if current:
                bullets.append(current)
            current = line[2:].strip()
        elif current is not None and line.strip():
            current += " " + line.strip()
        elif current:
            bullets.append(current)
            current = None
    if current:
        bullets.append(current)
    out = []
    for text in bullets:
        head, sep, rest = text.partition(":")
        if sep and len(head) < 60:
            out.append((head.strip(), rest.strip()))
        else:
            out.append(("Chain geometry", text))
    return out


def is_notation(title: str) -> bool:
    low = title.lower()
    return any(k in low for k in NOTATION_KEYWORDS)


def conventions_pages(repo_root: Path, repo: Repo):
    notation, definitions = [], []
    for rel in CONVENTION_SOURCES:
        path = repo_root / rel
        if not path.exists() or repo.classify(rel) != "public":
            continue
        blocks = (phase6_conventions(path) if path.suffix == ".md"
                  else tex_paragraphs(path))
        for title, body in blocks:
            if not body.strip():
                continue
            target = notation if is_notation(title) else definitions
            target.append((rel, title or "Preamble", body, path.suffix))

    def render(kind: str, heading: str, blurb: str, blocks) -> str:
        caveat = ("*This page is assembled mechanically from the LaTeX conventions "
                  "appendices of the two papers and the conventions block of the "
                  "phase-6 brief. Cross-references survive only as their raw "
                  "labels, and there is no curated symbol table yet: a human pass "
                  "is still owed. Read the appendices themselves if a symbol here "
                  "is unclear.*")
        out = [HAND_EDIT_BANNER, "", f"# {heading}", "", caveat, "", blurb, "",
               "Assembled from " + ", ".join(
                   f"[`{r}`]({rel_link(kind, r)})" for r in CONVENTION_SOURCES)
               + ". Mathematics is reproduced as LaTeX; a renderer that supports "
                 "it will typeset it, and the sources above are authoritative.", ""]
        seen = None
        for rel, title, body, suffix in blocks:
            if rel != seen:
                out += [f"## From `{rel}`", ""]
                seen = rel
            out += [f"### {esc(title)}", ""]
            out += [body if suffix == ".tex" else esc(body), ""]
        out += ["---", "",
                "[Documentation map](index.md) · [All claims by area](status.md)", ""]
        return "\n".join(out)

    note = render("notation.md", "Symbols and conventions",
                  "Every constant quoted in this project depends on the choices "
                  "collected here. This page is a first assembly from the "
                  "conventions of the two papers and of the Phase 6 brief; it is "
                  "meant to be read once by a human and corrected, after which "
                  "the marker line at the top stops the generator from touching "
                  "it again.", notation)
    defn = render("definitions.md", "The objects, and what they mean",
                  "The objects the results are about: the compression map, the "
                  "stress tensor normalisation, fidelity and relative entropy, "
                  "the one-sided recovery step and the Schwarzian corner data. "
                  "Like the notation page, this is a first assembly awaiting a "
                  "human pass.", definitions)
    return note, defn


