_ESCAPES = [
    (re.compile(r"\\"), r"\\\\"),
    (re.compile(r"`"), r"\\`"),
    (re.compile(r"\*"), r"\\*"),
    (re.compile(r"(?<![A-Za-z0-9])_"), r"\\_"),
    (re.compile(r"\["), r"\\["),
    (re.compile(r"\]"), r"\\]"),
    (re.compile(r"<"), r"\\<"),
    (re.compile(r"&(?=[A-Za-z#])"), r"\\&"),
    (re.compile(r"~"), r"\\~"),
]


def esc(text: str) -> str:
    """Escape the Markdown metacharacters, so that card text renders as itself.

    The knowledge base is plain ASCII mathematics (``V^*V``, ``[D_z, 0.71 f2
    z^2]``, ``x <= y``); without this a renderer would silently italicise or
    swallow parts of a statement, and the page would no longer be verbatim.
    """
    for pattern, repl in _ESCAPES:
        text = pattern.sub(repl, text)
    out = []
    for line in text.splitlines():
        out.append(re.sub(r"^(\s*)([-+>#=]|[0-9]+\.)", r"\1\\\2", line))
    return "\n".join(out)


def cell(text: str) -> str:
    """Escape for a table cell: as esc(), plus the column separator."""
    return esc(text).replace("|", "\\|").replace("\n", " ")


def badge(status: str) -> str:
    return f"`{status}`" if status else "`unrecorded`"


def rel_link(from_page: str, target: str) -> str:
    """Link from a page under docs/ to a repository path."""
    depth = from_page.count("/")
    return "../" * (depth + 1) + target


