def first_sentence(text: str) -> str:
    text = " ".join(text.split())
    m = re.search(r"(?<=[.])\s+(?=[A-Z(\[])", text)
    lead = text[:m.start()] if m else text
    if lead.count("`") % 2:
        lead += "`"
    if lead.count("**") % 2:
        lead += "**"
    return lead


# A source file may assert that a PDF is "already in refs/..." or name one by path.
# Both are true of this working tree and false of a clone, where refs/*.pdf is not
# redistributed, so the generated pages drop the assertion (REF-MOVE-1b, 1c).  The
# source files themselves are historical records and are never rewritten.
def _no_presence_claim(text: str) -> str:
    text = re.sub(r"\s*\(already in [^)]*\)", "", text)
    # keep the annotation OUTSIDE any surrounding backticks: the path is code, the
    # remark about it is not (REF-MOVE-1d)
    text = re.sub(r"`refs/([A-Za-z0-9_.+-]+\.pdf)`", r"`\1` (not redistributed)", text)
    text = re.sub(r"\brefs/([A-Za-z0-9_.+-]+\.pdf)\b", r"\1 (not redistributed)", text)
    return text


def history_page(repo_root: Path, repo: Repo) -> str:
    files = sorted((repo_root / "rigor").glob("PHASE*_STATUS.md"),
                   key=lambda p: (len(p.name), p.name))
    out = [BANNER, "", "# Phases 1 to 6: what each settled", "",
           "The project ran in six phases, each opened with a brief and closed "
           "with a status file. The lead of every entry of those status files is "
           "reproduced below, in order; each phase links to its full file, which "
           "carries the numbers, the verdicts and the corrections made on the "
           "day.", ""]
    for path in files:
        rel = str(path.relative_to(repo_root))
        if repo.classify(rel) != "public":
            continue
        lines = path.read_text(encoding="utf-8").splitlines()
        title = next((l[2:].strip() for l in lines if l.startswith("# ")), path.stem)
        out += [f"## {title}", "",
                f"Source: [`{rel}`]({rel_link('history.md', rel)})", ""]
        section, bullet = None, None
        pending = []

        def flush():
            if bullet is not None:
                # a status file may name a file a clone will not have; the file itself
                # is the historical record and stays as written, the page does not
                pending.append("- " + _no_presence_claim(first_sentence(bullet)))

        for line in lines:
            if line.startswith("# "):
                continue
            if line.startswith("## "):
                flush()
                bullet = None
                if pending:
                    out.extend(pending)
                    out.append("")
                    pending = []
                section = line[3:].strip()
                out += [f"### {section}", ""]
            elif re.match(r"^[-*] ", line):
                flush()
                bullet = line[2:]
            elif bullet is not None and line.startswith(("  ", "\t")):
                bullet += " " + line.strip()
            elif line.strip() == "":
                flush()
                bullet = None
            elif line.lstrip().startswith("|"):        # a table: keep it intact
                flush()
                bullet = None
                pending.append(line.rstrip())
            else:
                flush()
                bullet = None
                pending += [first_sentence(line), ""]
        flush()
        if pending:
            out.extend(pending)
        out.append("")
    errata = "rigor/errata_log.md"
    out += ["## Errata", "",
            "Results that were wrong at some point were corrected rather than "
            "erased. Every correction is recorded, with its date and the "
            "document it touched, in "
            f"[`{errata}`]({rel_link('history.md', errata)}).", "",
            "---", "",
            "[Documentation map](index.md) · [All claims by area](status.md) · "
            "[What is open](open.md)", ""]
    return "\n".join(out)


