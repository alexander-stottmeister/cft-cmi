def tally(claims: list) -> list:
    counts = {}
    for card in claims:
        counts[card.status] = counts.get(card.status, 0) + 1
    ordered = [(s, counts[s]) for s in STATUS_ORDER if s in counts]
    ordered += sorted((s, n) for s, n in counts.items() if s not in STATUS_ORDER)
    return ordered


def status_page(claims: list, areas: dict, pages: set) -> str:
    counts = tally(claims)
    total = sum(n for _, n in counts)
    unreviewed = [c for c in claims if not c.reviewed]
    failed = [c for c in claims if c.review_failed]
    pending = [c for c in claims if c.review_pending]
    promoted = [c for c in claims if c.folder == "evidence"]
    out = [BANNER, "", "# Every claim, by area", "",
           f"{total} cards: {total - len(promoted)} claim cards of the knowledge "
           f"base, plus {len(promoted)} finding"
           f"{'' if len(promoted) == 1 else 's'} that has reached a status "
           "displayed here. The tally below is counted from the cards, not "
           "typed:", "",
           "| status | claims | what it means |", "|---|---:|---|"]
    for status, n in counts:
        out.append(f"| {badge(status)} | {n} | {esc(STATUS_GLOSS.get(status, '—'))} |")
    out += [f"| **total** | **{total}** | |", ""]

    paged = sum(1 for c in claims if c.has_page)
    out += [f"{paged} of them are {', '.join(badge(s) for s in PAGE_STATUSES)} "
            "and have a page of their own under "
            "[`results/`](results/); the remainder are listed here with their "
            "status only.", "",
            "A referee pass is not implied by a status. Of the cards listed "
            f"here, **{len(unreviewed)} ha"
            f"{'s' if len(unreviewed) == 1 else 've'} never been refereed** and "
            f"**{len(failed)} carr{'ies' if len(failed) == 1 else 'y'} a failed "
            "referee pass**, that is repairs asked for and not yet absorbed. "
            "Cards awaiting a pass after a recent change are marked too, but "
            "not counted here: that number moves with day-to-day editing of "
            "infrastructure cards that have no page. "
            "All three are marked in the tables below, as *never refereed*, "
            "*referee pass failed* and *review pending*. Nothing labelled "
            f"{badge('numerical')} is a theorem.", ""]

    by_area = {}
    for card in claims:
        by_area.setdefault(card.area or "(no area)", []).append(card)
    for area_id in sorted(by_area, key=lambda a: area_sort_key(areas, a)):
        area = areas.get(area_id)
        title = area.title if area else area_id
        out += [f'<a id="area-{area_id}"></a>', "", f"## {esc(title)}", ""]
        if area and area.statement:
            out += ["> " + esc(" ".join(area.statement.split())), ""]
        out += ["| status | claim | |", "|---|---|---|"]
        rows = sorted(by_area[area_id],
                      key=lambda c: (STATUS_ORDER.index(c.status)
                                     if c.status in STATUS_ORDER else 99, c.id))
        for card in rows:
            name = (f"[{cell(card.title)}](results/{card.id}.md)"
                    if card.id in pages else cell(card.title))
            note = ("never refereed" if not card.reviewed else
                    "referee pass failed" if card.review_failed else
                    "review pending" if card.review_pending else "")
            out.append(f"| {badge(card.status)} | {name} | {note} |")
        out.append("")
    out += ["---", "",
            "[Documentation map](index.md) · [What is open](open.md) · "
            "[Sources](sources.md) · [History](history.md)", ""]
    return "\n".join(out)


