ARXIV = re.compile(r"arXiv:([0-9]{4}\.[0-9]{4,5}|[a-z-]+/[0-9]{7})")
URL = re.compile(r"https?://\S+")
PAYWALLED = re.compile(r"paywalled|not downloadable|\bbook\b", re.IGNORECASE)
OPEN = re.compile(r"\bopen\b", re.IGNORECASE)


def classify_source(src: str):
    """(key, sentence).  Mirrors refs/restore.sh: a row is fetchable when its
    Source column carries an arXiv identifier or a URL; of the rest, a row is
    open access when the column says so and needs library access otherwise."""
    m = ARXIV.search(src)
    if m:
        return "fetch", f"fetchable by `refs/restore.sh --fetch` (arXiv:{m.group(1)})"
    m = URL.search(src)
    if m:
        return "fetch", "fetchable by `refs/restore.sh --fetch` (direct link)"
    if PAYWALLED.search(src):
        return "library", "needs library access"
    if OPEN.search(src):
        return "open", "open access, but `refs/restore.sh` cannot resolve it automatically"
    return "library", "needs library access"


def restore_sh_says(repo_root: Path):
    """Ask refs/restore.sh itself which rows it can fetch, so the claim on the
    page is the script's own, not a reimplementation of it.  Returns a set of
    short names, or None when the script cannot be run."""
    script = repo_root / "refs" / "restore.sh"
    if not script.exists():
        return None
    try:
        out = subprocess.run(["bash", str(script), "--list"], check=True,
                             capture_output=True, text=True,
                             cwd=str(repo_root)).stdout
    except (OSError, subprocess.CalledProcessError):
        return None
    fetchable = set()
    for line in out.splitlines():
        parts = line.split()
        if len(parts) >= 2 and parts[0] in ("arXiv", "open"):
            fetchable.add(parts[1])
    return fetchable


def sources_page(repo_root: Path, warnings: list) -> str:
    text = (repo_root / "refs" / "REFERENCES.md").read_text(encoding="utf-8")
    rows, bullets = [], []
    for line in text.splitlines():
        if line.startswith("|"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) < 5 or cells[0] in ("Short",) or set(cells[0]) <= set("-: "):
                continue
            rows.append(cells)
        elif re.match(r"^- +`", line):
            bullets.append(line)

    fetchable = restore_sh_says(repo_root)
    groups = {"fetch": [], "open": [], "library": []}
    for cells in rows:
        cells = [_no_presence_claim(c) for c in cells]
        key, sentence = classify_source(cells[2])
        groups[key].append((cells, sentence))
        if fetchable is not None:
            script_says = cells[0] in fetchable
            if script_says != (key == "fetch"):
                warnings.append(f"sources.md: refs/restore.sh and this script "
                                f"disagree about {cells[0]}")

    n = len(rows)
    heuristic_note = (
        "The split between *open access* and *needs library access* is a **guess**, not a "
        "measurement: `refs/restore.sh` reports both as MANUAL, so this page classifies them "
        "by keywords in the Source column of `refs/REFERENCES.md`. Expect misfilings; at the "
        "time of writing `DaleckiiKrein` and `Petz96` are two of them. Only the *fetchable* "
        "group is verified, by comparison with a live `refs/restore.sh --list`.")
    out = [BANNER, "", "# External sources, and whether you can obtain them", "",
           heuristic_note, "",
           f"This page covers **the {n} table rows of "
           "[`refs/REFERENCES.md`](../refs/REFERENCES.md)**. It is *not* a list "
           "of every external result the project relies on: further sources are "
           f"cited in that file as bullet entries rather than table rows "
           f"({len(bullets)} of them below the table), and the source documents "
           "themselves are third-party material that this repository does not "
           "redistribute. For the full picture read "
           "[`refs/REFERENCES.md`](../refs/REFERENCES.md), which also records the "
           "exact result used from each source.", "",
           "Three ways to obtain a row:", "",
           f"| | rows | meaning |", "|---|---:|---|",
           f"| fetchable | {len(groups['fetch'])} | "
           "[`refs/restore.sh --fetch`](../refs/restore.sh) downloads it (arXiv "
           "identifier or direct link in the Source column) |",
           f"| open access | {len(groups['open'])} | freely readable at the "
           "publisher (Project Euclid, EMS Press / PRIMS), but the Source column "
           "carries no link `refs/restore.sh` can follow, so fetch it by hand |",
           f"| library access | {len(groups['library'])} | paywalled journal or a "
           "book; a library or an open restatement is needed |", "",
           "`refs/restore.sh` with no argument lists what it would download and "
           "reports everything else as `MANUAL`; it does not distinguish "
           "open-access `MANUAL` rows from paywalled ones, which is the "
           "distinction this page adds.", ""]

    titles = {"fetch": "Fetchable by `refs/restore.sh`",
              "open": "Open access, fetch by hand",
              "library": "Needs library access"}
    for key in ("fetch", "open", "library"):
        out += [f"## {titles[key]} ({len(groups[key])})", "",
                "| short | reference | source column | used in |",
                "|---|---|---|---|"]
        for cells, _ in groups[key]:
            out.append(f"| `{cell(cells[0])}` | {cell(cells[1])} | "
                       f"{cell(cells[2])} | {cell(cells[3])} |")
        out.append("")

    out += ["## What is taken from each source", "",
            "Quoted from the `Results used` column of "
            "[`refs/REFERENCES.md`](../refs/REFERENCES.md); an empty entry means "
            "the file records none.", ""]
    for cells in rows:
        used = cells[4].strip() if len(cells) > 4 else ""
        out.append(f"- **{esc(cells[0])}** — " + (esc(used) if used
                   else "_no result recorded in the table_"))
    out += ["", "---", "",
            "[Documentation map](index.md) · [All claims by area](status.md)", ""]
    return "\n".join(out)


