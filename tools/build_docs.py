FOOTER = ("---\n\n[Documentation map](../index.md) · "
          "[All claims by area](../status.md) · "
          "[What is open](../open.md) · "
          "[Symbols](../notation.md) · [Definitions](../definitions.md)")


def result_page(card: Card, areas: dict, by_id: dict, pages: set, repo: Repo) -> str:
    if "/" in card.id or card.id.startswith("."):
        raise ValueError(f"card id {card.id!r} would write outside results/")
    page = f"results/{card.id}.md"
    area = areas.get(card.area)
    out = [BANNER, "", f"# {esc(card.title)}", "", status_line(card), ""]

    if not card.reviewed:
        out += ["> **Never refereed.** This card carries no referee record. "
                "It states what was found; no independent pass has tried to "
                "break it.", ""]
    elif card.review_pending:
        out += ["> **Referee pass pending.** This card has been changed since "
                "its last pass and is queued for review; the verdict below is "
                "the state of that queue, not an accepted result.", ""]
    elif card.review_failed:
        out += ["> **The last referee pass failed.** An independent pass has "
                "asked for repairs that the card has not yet absorbed. The "
                "verdict and its date are below; the report itself stays in the "
                "private knowledge base.", ""]

    bits = []
    if area:
        bits.append(f"**Area:** [{esc(area.title)}](../status.md#area-{card.area})")
    if card.type:
        bits.append(f"**Card type:** {esc(card.type)}")
    bits.append(f"**Knowledge-base id:** `{esc(card.id)}`")
    out += [" · ".join(bits), ""]

    out += ["## Statement", ""]
    out += [esc(card.statement) if card.statement else "_No statement recorded._", ""]

    labels, sentences, conditional = hypotheses(card)
    if sentences:
        out += ["## Hypotheses", "",
                ("This result is conditional: at least part of the statement "
                 "holds only where the hypotheses below hold. " if conditional else
                 "The statement is made under named hypotheses. ")
                + "The sentences are quoted from the statement above; read the "
                  "status badge only together with them.", ""]
        if labels:
            out += [f"Hypothesis labels used: {', '.join('`' + l + '`' for l in labels)}.", ""]
        for sentence in sentences:
            out.append("> " + esc(sentence).replace("\n", " "))
            out.append(">")
        out[-1] = ""

    out += ["## How to verify", ""]
    out += [esc(card.verify) if card.verify
            else "_No verification recipe recorded on this card._", ""]

    out += ["## Evidence", ""]
    if card.evidence:
        out += ["- " + render_evidence(t, repo, page, pages) for t in card.evidence]
    else:
        out.append("_No evidence tokens recorded on this card._")
    out.append("")

    out += ["## Related claims", ""]
    if card.related:
        out += ["- " + render_related(t, by_id, pages) for t in card.related]
    else:
        out.append("_None recorded._")
    out.append("")

    out += ["## Review", "", review_line(card), "",
            "The referee's report and the card's event log stay in the private "
            "knowledge base; only the verdict, the date and the referee are "
            "published here.", "", FOOTER, ""]
    return "\n".join(out)


