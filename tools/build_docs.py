#!/usr/bin/env python3
"""Generate the documentation pages under ``docs/`` from the knowledge base.

The knowledge base (a private repository of one Markdown card per claim) is the
single source of truth for what is proved, measured, conjectured or open.  This
script turns it into the public pages, so the documentation cannot drift away
from the mathematics:

    docs/index.md          the map: headline results, the pages, the claims by area
    docs/status.md         every claim, grouped by area, with status and link
    docs/results/<id>.md   one page per refereed / proved / numerical / conjectural claim
    docs/open.md           the open claims with the recorded next step, verbatim
    docs/sources.md        the table rows of refs/REFERENCES.md and how to obtain each
    docs/history.md        phases 1 to 6 and what each settled
    docs/notation.md       assembled once from the conventions appendices
    docs/definitions.md    assembled once from the conventions appendices

Everything except ``notation.md`` and ``definitions.md`` is regenerated whole on
every run.  Those two are assembled once and then left alone as soon as their
marker line says a human has edited them.

    tools/build_docs.py              regenerate docs/
    tools/build_docs.py --check      regenerate into a temporary directory and
                                     exit non-zero if the committed pages differ

Three rules this script enforces, because a documentation page can lie in ways a
status word cannot:

1.  A conditional result names its hypotheses on its own page.  Sentences of the
    card that carry a hypothesis label are quoted verbatim under "Hypotheses",
    and the status line says "Conditional" (the statement holds only under them)
    or "Stated under hypotheses" (the statement carries a hypothesis list).
2.  An evidence pointer into the private companion never becomes a dead link.
    Whether a path is public is decided by asking git whether it is tracked, not
    by a list kept in this file.
3.  A card that has never been refereed is marked as such, on its page and in
    status.md.
"""

