def open_page(claims: list, pages: set) -> str:
    def entry(card: Card) -> list:
        name = (f"### [{esc(card.title)}](results/{card.id}.md)"
                if card.id in pages else f"### {esc(card.title)}")
        mark = ("" if not card.reviewed else " · referee pass failed"
                if card.review_failed else " · review pending"
                if card.review_pending else "")
        mark = " · never refereed" if not card.reviewed else mark
        block = [name, "",
                 f"{badge(card.status)} · knowledge-base id `{esc(card.id)}`"
                 + mark, ""]
        if card.id not in pages and card.statement:
            block += [esc(card.statement), ""]
        if card.next:
            block += ["**next:** " + esc(" ".join(card.next.split())), ""]
        else:
            block += ["_No next step recorded on this card._", ""]
        return block

    openers = sorted((c for c in claims if c.status == "open"), key=lambda c: c.id)
    conj = sorted((c for c in claims if c.status == "conjectural"), key=lambda c: c.id)
    others = sorted((c for c in claims
                     if c.next and c.status in PAGE_STATUSES
                     and c.status != "conjectural"), key=lambda c: c.id)

    out = [BANNER, "", "# What is open", "",
           "Every `next:` field below is quoted verbatim from its knowledge-base "
           "card: this page records the concrete next step, not an aspiration. "
           "Project-management cards (paper edits, plans, infrastructure) are "
           "deliberately left out.", "",
           f"## Open questions ({len(openers)})", ""]
    for card in openers:
        out += entry(card)
    out += [f"## Conjectures ({len(conj)})", "",
            "Believed, with partial evidence, and not proved.", ""]
    for card in conj:
        out += entry(card)
    out += [f"## Settled claims that still record a next step ({len(others)})", "",
            "These carry a status of their own; the step recorded is what would "
            "sharpen or extend them.", ""]
    for card in others:
        out += entry(card)
    out += ["---", "",
            "[Documentation map](index.md) · [All claims by area](status.md)", ""]
    return "\n".join(out)


