HAND_EDIT_MARKER = re.compile(r"^[ \t]*<!--[ \t]*hand-edited:[ \t]*(yes|true)[ \t]*-->[ \t]*$",
                              re.IGNORECASE | re.MULTILINE)


def hand_edited(path: Path) -> bool:
    """True once a marker line of its own says a human has taken the file over."""
    if not path.exists():
        return False
    for line in path.read_text(encoding="utf-8").splitlines()[:20]:
        if HAND_EDIT_MARKER.match(line):
            return True
    return False


def build_all(kb: Path, repo_root: Path, docs: Path):
    claims, areas, kb_stats = load_kb(kb)
    by_id = {c.id: c for c in claims}
    pages = {c.id for c in claims if c.has_page}
    repo = Repo(repo_root)
    warnings = []

    # Sweep every claim's evidence, not only the ones that reach a page, so the
    # count of privately held targets is the project's and not this page set's.
    for card in claims:
        for token in card.evidence:
            kind, _, rest = token.partition(":")
            if kind.strip() == "ev" or not rest.strip():
                continue
            repo.classify(rest.strip().partition("#")[0])

    files = {}
    for card in claims:
        if card.has_page:
            files[f"results/{card.id}.md"] = result_page(card, areas, by_id,
                                                         pages, repo)
    counts = tally(claims)
    files["status.md"] = status_page(claims, areas, pages)
    files["open.md"] = open_page(claims, pages)
    files["sources.md"] = sources_page(repo_root, warnings)
    files["history.md"] = history_page(repo_root, repo)
    files["index.md"] = index_page(claims, areas, by_id, pages, counts)

    note, defn = conventions_pages(repo_root, repo)
    skipped_hand_edited = []
    for name, content in (("notation.md", note), ("definitions.md", defn)):
        if hand_edited(docs / name):
            warnings.append(f"{name}: marked hand-edited, left untouched")
            skipped_hand_edited.append(name)
        else:
            files[name] = content


    stats = {
        "claims": len(claims),
        "pages": len(pages),
        "private": list(repo.private),
        "missing": list(repo.missing),
        "unreviewed": sorted(c.id for c in claims if not c.reviewed),
        "unreviewed_pages": sorted(c.id for c in claims
                                   if not c.reviewed and c.has_page),
        "failed": sorted(c.id for c in claims if c.review_failed),
        "pending": sorted(c.id for c in claims if c.review_pending),
        "counts": counts,
        "kb": kb_stats,
        "warnings": warnings,
        "skipped_hand_edited": skipped_hand_edited,
    }
    return files, stats


# The generator owns exactly two things inside docs/: the top-level *.md pages it
# writes, and everything under results/.  docs/assets/, docs/explore/, docs/lib/
# and docs/data/ belong to the figure and site builders and are never scanned,
# never reported and never deleted here.
OWNED_SUBDIR = "results"
OWNED_SUFFIXES = (".md", ".markdown")


def owned(rel: str) -> bool:
    """True for a path inside docs/ that this generator is responsible for."""
    if not rel.endswith(OWNED_SUFFIXES):
        return False
    parts = rel.split("/")
    return len(parts) == 1 or parts[0] == OWNED_SUBDIR


def write_out(files: dict, docs: Path):
    (docs / "results").mkdir(parents=True, exist_ok=True)
    for name, content in sorted(files.items()):
        target = docs / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
    stale = []
    for path in sorted((docs / OWNED_SUBDIR).rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(docs).as_posix()
        if owned(rel) and rel not in files:
            path.unlink()
            stale.append(rel)
    return stale


def check(files: dict, docs: Path, skipped=()) -> int:
    skipped = list(skipped)
    missing, extra, changed = [], [], []
    for name, content in sorted(files.items()):
        path = docs / name
        if not path.exists():
            missing.append(name)
        elif path.read_text(encoding="utf-8") != content:
            changed.append(name)
    for path in sorted(docs.rglob("*")):        # orphans, within our own scope only
        if not path.is_file():
            continue
        rel = path.relative_to(docs).as_posix()
        if owned(rel) and rel not in files and rel not in skipped:
            extra.append(rel)
    if not (missing or extra or changed):
        print(f"build_docs --check: {len(files)} pages up to date")
        if skipped:
            print("  NOT CHECKED, marked hand-edited: " + ", ".join(sorted(skipped)))
            print("  a hand-edited page is never compared, so it can go stale silently;")
            print("  re-read it, or clear the marker to put it back under the guard.")
        return 0
    print("build_docs --check: the committed documentation has drifted from the "
          "knowledge base")
    for name in missing:
        print(f"  missing   {name}")
    for name in extra:
        fixable = "" if "/" in name else "  (top level: delete it by hand)"
        print(f"  stale     {name} (no claim generates it any more){fixable}")
    for name in changed:
        print(f"  differs   {name}")
        committed = (docs / name).read_text(encoding="utf-8").splitlines()
        diff = list(difflib.unified_diff(committed, files[name].splitlines(),
                                         fromfile=f"committed/{name}",
                                         tofile=f"generated/{name}", lineterm="",
                                         n=0))
        for line in diff[:12]:
            print(f"      {line[:160]}")
        if len(diff) > 12:
            print(f"      ... {len(diff) - 12} more diff lines")
    print("\nRun `tools/build_docs.py` (or `make docs`) and commit the result.")
    return 1


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="regenerate into a temporary directory and exit "
                         "non-zero if the committed pages differ")
    ap.add_argument("--kb", type=Path, default=DEFAULT_KB,
                    help=f"knowledge-base directory (default: {DEFAULT_KB})")
    ap.add_argument("--docs", type=Path, default=REPO / "docs",
                    help="documentation folder to write (default: docs/)")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args(argv)

    files, stats = build_all(args.kb, REPO, args.docs)

    if args.check:
        with tempfile.TemporaryDirectory() as tmp:
            scratch = Path(tmp) / "docs"
            write_out(files, scratch)
            files = {name: (scratch / name).read_text(encoding="utf-8")
                     for name in files}
        rc = check(files, args.docs, stats.get("skipped_hand_edited", ()))
    else:
        stale = write_out(files, args.docs)
        rc = 0
        if not args.quiet:
            print(f"build_docs: wrote {len(files)} pages to {args.docs}")
            for name in stale:
                print(f"  removed stale {name}")

    if not args.quiet:
        counts = ", ".join(f"{n} {s}" for s, n in stats["counts"])
        print(f"  claims {stats['claims']} ({counts})")
        print(f"  pages under results/: {stats['pages']}")
        print(f"  evidence pointers held privately, rendered without a link: "
              f"{len(stats['private'])}")
        for path in stats["private"]:
            print(f"      {path}")
        print(f"  cards never refereed: {len(stats['unreviewed'])} of the "
              f"{stats['claims']} listed ({len(stats['unreviewed_pages'])} with "
              f"a page); {stats['kb']['unreviewed']} of the "
              f"{stats['kb']['cards']} cards in the whole knowledge base, the "
              "rest being findings that reach no displayed status")
        print(f"  cards awaiting a referee pass: {len(stats['pending'])}"
              + (" (" + ", ".join(stats["pending"]) + ")" if stats["pending"] else ""))
        print(f"  cards whose last referee pass failed: {len(stats['failed'])}"
              + (" (" + ", ".join(stats["failed"]) + ")" if stats["failed"] else ""))
        for path in stats["missing"]:
            print(f"  WARNING evidence path neither public nor on disk: {path}")
        for warning in stats["warnings"]:
            print(f"  note: {warning}")
    return rc


if __name__ == "__main__":
    sys.exit(main())
