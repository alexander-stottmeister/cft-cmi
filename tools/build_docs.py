class Card:
    """One knowledge-base card: front matter plus the body sections."""

    def __init__(self, path: Path, meta: dict, sections: dict):
        self.path = path
        self.meta = meta
        self.sections = sections
        self.id = meta.get("id", path.stem)
        self.type = meta.get("type", "")
        self.title = meta.get("title", self.id)
        self.status = meta.get("status", "")
        self.area = meta.get("area", "")
        self.review = meta.get("review", "")
        self.next = meta.get("next", "")
        self.evidence = split_list(meta.get("evidence", ""))
        self.related = split_list(meta.get("related", ""))
        self.folder = path.parent.name

    @property
    def statement(self) -> str:
        return self.sections.get("Statement", "").strip()

    @property
    def verify(self) -> str:
        return self.sections.get("How to verify", "").strip()

    @property
    def reviewed(self) -> bool:
        return bool(self.review.strip())

    @property
    def review_failed(self) -> bool:
        return self.review.strip().lower().startswith("fail")

    @property
    def review_pending(self) -> bool:
        return self.review.strip().lower().startswith("pending")

    @property
    def has_page(self) -> bool:
        return self.status in PAGE_STATUSES


def split_list(value: str) -> list:
    return [p.strip() for p in value.split(",") if p.strip()]


def parse_card(path: Path) -> Card:
    text = path.read_text(encoding="utf-8")
    meta, body = {}, text
    if text.startswith("---"):
        end = text.find("\n---", 3)
        if end != -1:
            front = text[3:end]
            body = text[end + 4:]
            for line in front.splitlines():
                if not line.strip() or line.lstrip().startswith("#"):
                    continue
                if ":" not in line:
                    continue
                key, value = line.split(":", 1)
                key = key.strip()
                if key and not key[0].isspace():
                    meta[key] = value.strip()
    sections, name, buf = {}, None, []
    for line in body.splitlines():
        if line.startswith("## "):
            if name is not None:
                sections[name] = "\n".join(buf).strip()
            name, buf = line[3:].strip(), []
        elif name is not None:
            buf.append(line)
    if name is not None:
        sections[name] = "\n".join(buf).strip()
    return Card(path, meta, sections)


def load_kb(kb: Path):
    """Return (claims, areas, kb_stats).  A claim is any card that carries a
    status we display: every card of claims/, plus a card of evidence/ that has
    reached one of the page statuses (findings promoted to a result live there).
    kb_stats counts the whole base, including the findings that stay behind."""
    if not (kb / "claims").is_dir():
        sys.exit(f"build_docs: no knowledge base at {kb} (pass --kb PATH)")
    claims = [parse_card(p) for p in sorted((kb / "claims").glob("*.md"))]
    every = list(claims)
    for p in sorted((kb / "evidence").glob("*.md")):
        card = parse_card(p)
        every.append(card)
        if card.has_page:
            claims.append(card)
    areas = {c.id: c for c in (parse_card(p) for p in sorted((kb / "areas").glob("*.md")))}
    kb_stats = {"cards": len(every),
                "unreviewed": sum(1 for c in every if not c.reviewed)}
    return claims, areas, kb_stats


def area_sort_key(areas: dict, area_id: str):
    card = areas.get(area_id)
    try:
        order = int(card.meta.get("order", "99")) if card else 99
    except ValueError:
        order = 99
    return (order, area_id)


# --------------------------------------------------------------------------- #
# what is public, and what is held privately
# --------------------------------------------------------------------------- #

class Repo:
    """Read-only view of which repository paths are published.

    Eight evidence targets live only in the private companion (source PDFs that
    may not be redistributed, plus the two private checklists).  They are found
    by asking git which paths this repository tracks, so the list never has to be
    maintained here and cannot go stale.
    """

    def __init__(self, root: Path):
        self.root = root
        try:
            out = subprocess.run(
                ["git", "-C", str(root), "ls-files"],
                check=True, capture_output=True, text=True).stdout
        except (OSError, subprocess.CalledProcessError) as exc:
            sys.exit("build_docs: cannot ask git which files are public "
                     f"({exc}). The private-pointer check needs it; aborting "
                     "rather than publishing links that may 404.")
        self.tracked = {line for line in out.splitlines() if line}
        self.private = []      # paths that exist but are not published
        self.missing = []      # paths that are neither published nor on disk

    def classify(self, relpath: str) -> str:
        """'public', 'private' or 'missing'."""
        if relpath in self.tracked:
            return "public"
        if (self.root / relpath).exists():
            if relpath not in self.private:
                self.private.append(relpath)
            return "private"
        if relpath not in self.missing:
            self.missing.append(relpath)
        return "missing"


