def build_separation():
    """docs/data/extra-separation.json.

    The exact constrained minima of e^{Delta_k} under "every corner to the
    right is weak", against the bound 2/eps of Theorem 11.1.  The bound is
    approached and never attained: the ratio column is the whole point."""
    records = []

    src, lines = read("rigor/ref_p6_3_separation.out")
    declare(src, lines, "EXACT minimum of e^{Delta_k} over all-weak chains "
                        "(m = number of corners j >= k)",
            "the meaning of the m columns")
    h = header(src, lines,
               r"^\s*eps\s+m=1\s+m=2\s+m=3\s+m=10\s+m->inf\s+2/eps\s+ratio\s*$",
               "the exact-minimum table")
    cols = ["m1", "m2", "m3", "m10", "inf"]
    seen = 0
    for i in range(h + 1, len(lines)):
        v = nums(lines[i])
        if len(v) != 8:
            break
        seen += 1
        eps, ln1 = v[0], i + 1
        for j, key in enumerate(cols):
            records.append(record(
                "sep.min.%s.%s" % (key, eps), v[1 + j], None, src, ln1, "numerical",
                series="min_" + key, x=eps,
                label=("exact constrained minimum of e^{Delta_k}, %s corners to the right, eps = %s"
                       % ({"inf": "arbitrarily many"}.get(key, key[1:]), eps))))
        records.append(record("sep.bound.%s" % eps, v[6], None, src, ln1, "proved",
                              series="bound", x=eps,
                              label="the bound 2/eps of Theorem 11.1 at eps = %s" % eps))
        records.append(record("sep.ratio.%s" % eps, v[7], None, src, ln1, "numerical",
                              series="ratio", x=eps,
                              label="(eps/2) times the exact minimum at eps = %s: 1 would be attainment"
                                    % eps))
    if seen != 5:
        raise Drift("%s: expected 5 rows of exact minima, read %d" % (src, seen))

    # the checks that say the theorem is never violated, and the escape routes
    for rid, pat, status, label in [
        ("sep.check.random_exact",
         r"separation e\^\{Delta_k\} >= 2/eps\s+\(0 violations, min \(eps/2\)e\^\{Delta\} = (%s)\)" % _NUM,
         "numerical", "min (eps/2)e^{Delta_k} over 60000 exact rational chains (REF-P6-3)"),
        ("sep.check.admissible",
         r"Cor 11\.2: eps e\^\{Delta_k\} >= 1 for admissible s_j \(min = (%s)\)" % _NUM,
         "numerical", "min eps e^{Delta_k} for admissible s_j in [lambda, 2 lambda] (Corollary 11.2)"),
        ("sep.check.pair_only",
         r"the separation stays O\(1\): min e\^\{Delta_k\} found = (%s)" % _NUM,
         "numerical", "with only the PAIR of corners weak at eps = 0.01: the separation stays O(1), "
                      "against 2/eps = 200"),
    ]:
        rx = re.compile(pat)
        for i, ln in enumerate(lines):
            m = rx.search(ln)
            if m:
                records.append(record(rid, float(m.group(1)), None, src, i + 1, status,
                                      series="check", label=label))
                break
        else:
            raise Drift("%s: no line matching %r" % (src, pat))

    src2, lines2 = read("rigor/g1a_separation.out")
    for rid, pat, label in [
        ("sep.check.random_float",
         r"min over 400000 random chains of \(eps/2\) e\^\{D_k\} = (%s)" % _NUM,
         "min (eps/2)e^{Delta_k} over 400000 random chains (G1a)"),
        ("sep.check.last_corner",
         r"min over the same chains of e\^\{D_\{n-1\}\}/\(1\+2/zeta_\{n-1\}\) = (%s)" % _NUM,
         "e^{Delta_{n-1}}/(1+2/zeta_{n-1}) over the same chains: the last corner is an equality"),
    ]:
        rx = re.compile(pat)
        for i, ln in enumerate(lines2):
            m = rx.search(ln)
            if m:
                records.append(record(rid, float(m.group(1)), None, src2, i + 1, "numerical",
                                      series="check", label=label))
                break
        else:
            raise Drift("%s: no line matching %r" % (src2, pat))

    return {
        "generator": "tools/build_site_data_extra.py",
        "module": "separation",
        "note": ("Theorem 11.1 of rigor/network_corner_calculus.tex and the exact constrained "
                 "minima REF-P6-3 computed from the backward recursion of Lemma 10.3.  The module "
                 "runs the same recursion live, so its own curve can be read against these "
                 "numbers; m is the number of corners to the right of p_k."),
        "records": records,
    }


