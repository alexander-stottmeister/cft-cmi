THERMAL = "numerics/lattice/petz_thermal_rg.out"


def _rows_after(lines, h, count):
    """Yield (1-based line number, [numbers]) for the rows that follow the
    column header at index `h` and still have `count` numbers on them."""
    for i in range(h + 1, len(lines)):
        v = nums(lines[i])
        if len(v) != count:
            return
        yield i + 1, v


def _thermal(records):
    """Section (1): -log F and the CMI of a KMS state against L_B/beta, and
    section (1a): the fitted shielding rates."""
    src, lines = read(THERMAL)
    declare(src, lines,
            "L_A = L_C = L, L_B = b, v = 2, beta_len = 2 beta, xi = beta/pi",
            "the thermal length units of the b/beta axis")
    blk = re.compile(r"^\s*L_A=L_C=(\d+)\s+beta=([\d.]+)\s*$")
    hdr = (r"^\s*b/beta\s+-logF\^\(0\)\s+/vacuum\s+CMI\s+CMI_cont\s+kap_F\s+kap_I"
           r"\s+kap_Ic\s+ratio 2br\s*$")
    blocks = 0
    for i, ln in enumerate(lines):
        m = blk.match(ln)
        if not m or m.group(1) != "8":
            continue                      # one geometry on the page: L_A = L_C = 8
        L, beta = m.group(1), m.group(2)
        h = header(src, lines, hdr, "the thermal table at beta = %s" % beta, start=i)
        if h != i + 1:
            raise Drift("%s: the column header does not follow the block line at %d" % (src, i + 1))
        blocks += 1
        for ln1, v in _rows_after(lines, h, 9):
            x = v[0]
            records.append(record("th.phi.b%s.%s" % (beta, x), v[1], None, src, ln1, "numerical",
                                  series="thermal.phi.b" + beta, x=x,
                                  label="-log F^(0) at L_B/beta = %s, beta = %s, L_A = L_C = %s"
                                        % (x, beta, L)))
            records.append(record("th.cmi.b%s.%s" % (beta, x), v[3], None, src, ln1, "numerical",
                                  series="thermal.cmi.b" + beta, x=x,
                                  label="I(A:C|B) at L_B/beta = %s, beta = %s, L_A = L_C = %s"
                                        % (x, beta, L)))
    if blocks != 4:
        raise Drift("%s: expected 4 finite-beta thermal blocks at L = 8, found %d" % (src, blocks))

    declare(src, lines, "fit -log F^(0) = A exp(-kappa_F L_B/beta)",
            "the rate kappa is measured in units of beta")
    declare(src, lines, "kappa_I = pi = 3.14159 and, if -log F ~ eta^2, kappa_F = 2 pi = 6.28319",
            "the continuum values the fitted rates are read against")
    h = header(src, lines,
               r"^\s*L\s+beta\s+#pts\s+kappa_F\s+A_F\s+kappa_I\s+A_I\s+kappa_F/kappa_I"
               r"\s+kappa_I\(cont\)\s*$", "the shielding-rate fits")
    fits = 0
    for ln1, v in _rows_after(lines, h, 9):
        fits += 1
        tag = "L%d.b%s" % (int(v[0]), v[1])
        records.append(record("th.kapF." + tag, v[3], None, src, ln1, "numerical",
                              series="rate.kapF", x=v[1], L=v[0],
                              label="fitted kappa_F at L = %d, beta = %s (continuum 2 pi)"
                                    % (int(v[0]), v[1])))
        records.append(record("th.kapI." + tag, v[5], None, src, ln1, "numerical",
                              series="rate.kapI", x=v[1], L=v[0],
                              label="fitted kappa_I at L = %d, beta = %s (continuum pi)"
                                    % (int(v[0]), v[1])))
    if fits != 6:
        raise Drift("%s: expected 6 rows of shielding fits, read %d" % (src, fits))


def _cfunction(records):
    """Section (2): the entropic and Markov c-functions along the massive flow."""
    src, lines = read(THERMAL)
    declare(src, lines, "staggered mass m, mu = m/2, xi = 2/m sites, RG variable mu R = m R/2",
            "the RG variable mu R of the c-function axis")
    declare(src, lines, "PRIMARY DEFINITION c_M := c_M^(2) = 3R^2 I_{R-2}(2)/4",
            "which column is the Markov c-function")
    blk = re.compile(r"^\s*m = ([\d.]+)\s+xi = (\S+) sites\s*$")
    hdr = (r"^\s*R\s+mu R\s+c_E\s+c_M=c_M\^\(2\)\s+c_M\^\(4\)\s+c_M\^\(Rich\)\s+c_M/c_E"
           r"\s+\(c_M/c_E\)/\(mR\)\s+dc_E\s+dc_M\s*$")
    masses = []
    for i, ln in enumerate(lines):
        m = blk.match(ln)
        if not m:
            continue
        mass = m.group(1)
        h = header(src, lines, hdr, "the c-function table at m = %s" % mass, start=i)
        if h != i + 1:
            raise Drift("%s: the c-function header does not follow the block line at %d"
                        % (src, i + 1))
        masses.append(mass)
        for ln1, v in _rows_after(lines, h, 10):
            R = int(v[0])
            records.append(record("cf.cE.m%s.R%d" % (mass, R), v[2], None, src, ln1, "numerical",
                                  series="cfun.cE.m" + mass, x=v[1], R=R,
                                  label="entropic c_E(R = %d) at m = %s" % (R, mass)))
            records.append(record("cf.cM.m%s.R%d" % (mass, R), v[3], None, src, ln1, "numerical",
                                  series="cfun.cM.m" + mass, x=v[1], R=R,
                                  label="Markov c_M(R = %d) at m = %s" % (R, mass)))
            records.append(record("cf.rmr.m%s.R%d" % (mass, R), v[7], None, src, ln1, "numerical",
                                  series="cfun.ratio_mR.m" + mass, x=v[1], R=R,
                                  label="(c_M/c_E)/(mR) at R = %d, m = %s: the IR prediction is 1"
                                        % (R, mass)))
    if masses != ["0.0000", "0.0500", "0.1000", "0.2000", "0.4000", "0.8000", "1.6000"]:
        raise Drift("%s: the mass ladder of section (2) changed: %r" % (src, masses))
    return masses


def _gap(records):
    """Section (3): the gap geometry A | G | B | C with G traced out."""
    src, lines = read(THERMAL)
    declare(src, lines,
            "I(A:C|B) = (1/3) log[(a+g+b)(g+b+c)/((g+b)(a+g+b+c))],",
            "the closed-form gap law the module evaluates live")
    declare(src, lines, "eta_g = a c/[(a+g+b)(g+b+c)] -> a c/L_G^2, so I ~ L_G^-2, -logF ~ L_G^-4",
            "the naive expectation the measurement contradicts")
    # The three gap tables carry no L column: the driver decides, and it is the
    # only place that says so, so the lengths are read from there and guarded.
    drv, dlines = read("numerics/lattice/petz_thermal_rg.py")
    ln = declare(drv, dlines, "for L in (6, 8, 12): rows += gap_scan(L=L,",
                 "which interval length each of the three gap tables belongs to")
    lengths = [int(x) for x in re.findall(r"\d+", dlines[ln - 1].split("(")[1].split(")")[0])]
    if lengths != [6, 8, 12]:
        raise Drift("%s:%d: the gap scan no longer runs L = 6, 8, 12" % (drv, ln))

    at, total = 0, 0
    for L in lengths:
        h = header(src, lines,
                   r"^\s*L_G\s+eta_g\s+I\(A:C\|B\)\s+I_cont\s+I/I_cont\s+-logF\^\(0\)\s+-logF\^\(1\)"
                   r"\s+ratio 2br\s+p_I\s+p_F\s+-logF/I\s+norm\s*$",
                   "the gap table at L = %d" % L, start=at)
        at = h + 1
        rows = 0
        for ln1, v in _rows_after(lines, h, 12):
            rows += 1
            g = int(v[0])
            records.append(record("gap.I.L%d.%d" % (L, g), v[2], None, src, ln1, "numerical",
                                  series="gap.I.L%d" % L, x=g, L=L,
                                  label="measured I(A:C|B) at L_G = %d, L_A = L_B = L_C = %d" % (g, L)))
            records.append(record("gap.Icont.L%d.%d" % (L, g), v[3], None, src, ln1, "numerical",
                                  series="gap.Icont.L%d" % L, x=g, L=L,
                                  label="the closed-form gap law at L_G = %d, L = %d" % (g, L)))
            records.append(record("gap.phi.L%d.%d" % (L, g), v[5], None, src, ln1, "numerical",
                                  series="gap.phi.L%d" % L, x=g, L=L,
                                  label="-log F^(0) at L_G = %d, L = %d" % (g, L)))
            records.append(record("gap.ratio.L%d.%d" % (L, g), v[10], None, src, ln1, "numerical",
                                  series="gap.ratio.L%d" % L, x=g, L=L,
                                  label="-log F^(0) / I at L_G = %d, L = %d: the ratio tends to a "
                                        "constant, so the decay is linear in the CMI, not quadratic"
                                        % (g, L)))
        if rows != 14:
            raise Drift("%s: expected 14 rows of gap geometry at L = %d, read %d" % (src, L, rows))
        total += rows
    if total != 42:
        raise Drift("%s: expected three gap tables, read %d rows" % (src, total))


def _two_branch(records):
    """The lattice exponents of -log F^(lambda) ~ eta^p."""
    src, lines = read("numerics/lattice/petz_lattice.out")
    declare(src, lines, "apparent exponents p of -log F^(lam) ~ eta^p (least squares in log-log)",
            "what the exponent columns measure")
    h = header(src, lines,
               r"^\s*lambda\s+eta<=0\.1\s+0\.02-0\.2\s+0\.05-0\.5\s+\|\s+VWZ fit\s+Note 5\s*$",
               "the two-branch exponent table")
    rows = 0
    for i in range(h + 1, len(lines)):
        m = re.match(r"^\s*(%s)\s+(%s)\s+(%s)\s+(%s)\s+\|\s+(%s)\s+(%s)\s" % ((_NUM,) * 6), lines[i])
        if not m:
            break
        rows += 1
        lam = m.group(1)
        records.append(record("tb.p.%s" % lam, float(m.group(2)), None, src, i + 1, "numerical",
                              series="twobranch.lattice", x=float(lam),
                              label="lattice exponent p at lambda = %s, fitted over eta <= 0.1" % lam))
        records.append(record("tb.vwz.%s" % lam, float(m.group(5)), None, src, i + 1, "numerical",
                              series="twobranch.vwz", x=float(lam),
                              label="the Vardhan-Wei-Zou fitted exponent at lambda = %s" % lam))
    if rows != 4:
        raise Drift("%s: expected 4 rows of exponents, read %d" % (src, rows))


