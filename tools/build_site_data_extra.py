def _ls_files(args, why, required=True):
    try:
        out = subprocess.run(["git"] + args + ["ls-files", "-z"], cwd=str(ROOT),
                             capture_output=True, text=True, check=True).stdout
    except (OSError, subprocess.CalledProcessError) as exc:
        if required:
            raise Drift("cannot list %s (%s); the public/private test must not be "
                        "hard-coded" % (why, exc))
        return set()
    return {p for p in out.split("\0") if p}


def tracked_files():
    """(public, private): what each of the two repositories over this one work
    tree tracks.  Membership is the definition of "published": the public
    repository and the private companion share the tree, so a file being present
    on disk says nothing about whether it ships.  A file the private repository
    tracks is held privately; a file neither tracks is simply not committed yet,
    and is reported as such rather than as either."""
    public = _ls_files(["-C", str(ROOT)], "the tracked files")
    if not public:
        raise Drift("git ls-files returned nothing: refusing to mark every pointer private")
    private = _ls_files(["--git-dir", ".git-private"], "the private companion", required=False)
    return public, private


def _front_matter(path):
    """(frontmatter dict, {section title: body}) of one knowledge-base card."""
    text = path.read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    if not m:
        raise Drift("%s: no frontmatter" % path)
    fm = {}
    for line in m.group(1).split("\n"):
        k = re.match(r"^([a-z_]+):\s*(.*)$", line)
        if k:
            fm[k.group(1)] = k.group(2).strip()
    body, sections, title = m.group(2), {}, None
    for line in body.split("\n"):
        h = re.match(r"^##\s+(.*)$", line)
        if h:
            title = h.group(1).strip()
            sections[title] = []
        elif title:
            sections[title].append(line)
    return fm, {k: "\n".join(v).strip() for k, v in sections.items()}


def _evidence(token, public, private):
    """Resolve one evidence token to a pointer the page can render.

    A pointer into the private companion is returned with access "private" and
    no href, so the module shows "held privately" instead of a dead link."""
    kind, _, rest = token.partition(":")
    if kind not in ("doc", "num", "ref", "ev") or not rest:
        return None
    if kind == "ev":
        return {"kind": kind, "target": rest, "access": "kb"}
    path, _, anchor = rest.partition("#")
    out = {"kind": kind, "path": path, "anchor": anchor or None}
    if path in public:
        out["access"] = "public"
    elif path in private:
        out["access"] = "private"
    elif (ROOT / path).exists():
        out["access"] = "uncommitted"
    else:
        out["access"] = "missing"
    return {k: v for k, v in out.items() if v is not None}


# A card's prose may name a file that only the private companion carries.  The map
# publishes that prose verbatim, so mark such a path rather than let it read as
# something the reader could open (REF-MOVE-1g).  The cards themselves are the
# record and are never rewritten.
_PRIVATE_PATH = re.compile(
    r"\b(PRIVATE\.md|CHECKLIST\.md|pgit-exclude|pgit|rigor/shots(?:/[A-Za-z0-9_.+-]+)?|"
    r"plan_page(?:/[A-Za-z0-9_.+-]+)?|"
    r"refs/[A-Za-z0-9_.+-]+\.pdf|rigor/cited_R[1-4]\.tex|rigor/cited_results_all\.tex)\b")


# The masking rule below is path-shaped: it looks at evidence tokens and hides the
# ones git does not track.  On 2026-09-23 REF-LIVE found a leak that was prose-shaped
# instead -- a card Statement carrying the address of a privately held Claude artifact,
# with an instruction to open it, rendered as text by module 10 and served to the world.
# A host allow-list closes the class rather than the instance: anything in a payload that
# looks like a link must point somewhere we have decided to publish.
#
# REF-LEAK then broke the first version of this guard six ways, so it no longer trusts a
# field list or a single pattern.  check_payload() sweeps the SERIALISED json, which is
# what ships, so it covers every field including the ones nobody thought of; and the host
# is taken after the last '@', because https://github.com:1234@elsewhere/ is not github.
ALLOWED_PROSE_HOSTS = {"github.com", "alexander-stottmeister.github.io",
                       "projecteuclid.org", "arxiv.org", "doi.org",
                       "creativecommons.org", "orcid.org", "www.w3.org"}
# REF-GUARD broke the previous version nine ways.  Four of them mattered and all four
# are answered here rather than by adding patterns:
#   * a label separator a browser accepts and ASCII does not -- soft hyphen, zero width,
#     fullwidth and ideographic stops -- so the text is NFKC-normalised and the invisible
#     code points are stripped BEFORE anything is matched;
#   * `?` and `#` end an authority, so they must not be inside the host class, or
#     https://elsewhere.example?@github.com reads as github.com, which is the regression
#     the fix for the userinfo trick introduced;
#   * a scheme other than http(s) is never publishable here, so it is rejected outright
#     rather than parsed, which covers file:, data:, ftp: and anything later;
#   * the bare-host branch needs a suffix list, and a short one is a hole, so it takes any
#     label of two or more letters and accepts the cost of an occasional false positive:
#     this guard may only be too strict, never too lax.
_INVISIBLE = dict.fromkeys(map(ord, "\u00ad\u200b\u200c\u200d\u2060\ufeff"))
# A deny-list, not "any scheme": prose is full of words followed by a colon, and
# http(s) is handled by the authority branch below.
_SCHEME = re.compile(r"\b(data|javascript|vbscript|file|ftp|ftps|ws|wss|blob|about|chrome|resource|view-source)\s*:", re.I)
_AUTHORITY = re.compile(r"(?:[a-z][a-z0-9+.-]*:)?//([^/?#\s)>\]\"'\\]+)", re.I)
# A bare host only counts when it is followed by a path and is not itself a path
# segment, or every dotted filename in the corpus (lb.log, README.md, x.json) is a host.
_BARE_HOST = re.compile(r"(?<![/\w.-])((?:[a-z0-9-]+\.)+[a-z]{2,})(?=/)", re.I)


def _fold(text: str) -> str:
    """What a browser would see: no invisible separators, compatibility-normalised."""
    return unicodedata.normalize("NFKC", (text or "").translate(_INVISIBLE))


def _host_of(raw: str) -> str:
    host = raw.rsplit("@", 1)[-1]                 # strip any userinfo
    return host.split(":")[0].strip().lower().rstrip(".")


def _foreign_hosts(text: str):
    """Every host in `text` that is not on the allow-list, plus any unpublishable scheme."""
    folded = _fold(text)
    for m in _SCHEME.finditer(folded):
        yield "a %s: URL" % m.group(1).lower()
    seen = set()
    for m in list(_AUTHORITY.finditer(folded)) + list(_BARE_HOST.finditer(folded)):
        host = _host_of(m.group(1))
        if host and host not in ALLOWED_PROSE_HOSTS and host not in seen:
            seen.add(host)
            yield host


def check_payload(name: str, payload) -> None:
    """Refuse to ship a payload that links off the allow-list, whatever field it is in.

    The sweep is over the SERIALISED json, which is what ships, so it covers every field
    including the ones nobody thought of -- the leak of 2026-09-23 was in a field the
    first version of this guard did not list."""
    bad = {}
    for host in _foreign_hosts(json.dumps(payload, ensure_ascii=False)):
        bad[host] = bad.get(host, 0) + 1
    if bad:
        raise Drift("docs/data/%s would publish %s. Card prose and every other field ship "
                    "verbatim to the public site; move the address somewhere private, or add "
                    "the host to ALLOWED_PROSE_HOSTS if it is meant to be published."
                    % (name, ", ".join("%d link(s) on %s" % (n, h) for h, n in sorted(bad.items()))))


def _no_foreign_url(text: str, cid: str, field: str) -> str:
    """Name the card and the field, so check_payload's message is actionable.

    The payload sweep is the guard; this is the diagnosis, and it runs first so the
    error says which card to fix rather than only which file would have shipped."""
    for host in _foreign_hosts(text):
        if True:
            raise Drift("card %s, field %s, publishes a link on %s, which is not in "
                        "ALLOWED_PROSE_HOSTS. Card prose ships verbatim to the public "
                        "site; move the address somewhere private, or add the host there "
                        "if it is meant to be published." % (cid, field, host))
    return text


def _mark_private(text: str) -> str:
    seen = set()

    def one(m):
        path = m.group(1)
        if path in seen:
            return path
        seen.add(path)
        return "%s (held privately)" % path
    return _PRIVATE_PATH.sub(one, text or "")


def build_claim_map():
    """docs/data/extra-claim-map.json: every knowledge-base card, its status,
    its evidence and the graph of the areas.

    The knowledge base itself is not published, so the module is the only public
    view of it.  Two rules are enforced here rather than in the page: a card
    whose frontmatter records no referee verdict is marked never-refereed, and
    an evidence pointer whose target is not tracked by git is marked private."""
    if not KB.is_dir():
        raise Drift("the knowledge base is not at %s" % KB)
    public, private = tracked_files()

    areas = []
    for p in sorted((KB / "areas").glob("*.md")):
        fm, _ = _front_matter(p)
        areas.append({"id": fm["id"], "title": fm.get("title", fm["id"]),
                      "status": fm.get("status", "active"),
                      "order": int(fm.get("order", "99"))})
    areas.sort(key=lambda a: (a["order"], a["id"]))
    if not areas:
        raise Drift("no areas in the knowledge base")

    cards, priv, pub, kbp, missing, never, uncommitted = [], 0, 0, 0, 0, 0, 0
    pending = 0
    priv_targets = set()
    # Which cards the map shows, and why: every card of claims/, plus a card of
    # evidence/ that has reached a displayed status, which is the rule
    # tools/build_docs.py uses for the generated pages.  Holding the two
    # surfaces to one rule is the point: a card on one and not the other would
    # be a card quietly left out.  The findings that stay behind are counted.
    PROMOTED = ("refereed", "proved", "numerical", "conjectural")
    sources = [(p, "claims") for p in sorted((KB / "claims").glob("*.md"))]
    findings_left = 0
    for p in sorted((KB / "evidence").glob("*.md")):
        fm0, _ = _front_matter(p)
        if fm0.get("status", "").strip() in PROMOTED:
            sources.append((p, "evidence"))
        else:
            findings_left += 1
    for p, origin in sources:
        fm, sec = _front_matter(p)
        review = fm.get("review", "").strip()
        verdict = re.match(r"^(passed|FAILED)\b", review)
        # A card may say "pending" while its history already records verdicts:
        # that is awaiting a re-review, which is not the same as never refereed.
        past = re.findall(r"^-\s+\S+\s+review (passed|FAILED)\b", sec.get("History", ""), re.M)
        refereed = bool(verdict) or bool(past)
        awaiting = bool(re.match(r"^pending\b", review)) or not review
        if not refereed:
            never += 1
        if awaiting:
            pending += 1
        evid = []
        for tok in re.split(r",\s*", fm.get("evidence", "")):
            tok = tok.strip()
            if not tok:
                continue
            e = _evidence(tok, public, private)
            if e is None:
                continue
            if e.get("access") == "private":
                priv_targets.add(e["path"])
            priv += e.get("access") == "private"
            pub += e.get("access") == "public"
            kbp += e.get("access") == "kb"
            missing += e.get("access") == "missing"
            uncommitted += e.get("access") == "uncommitted"
            evid.append(e)
        page = "%s.md" % fm["id"]
        cards.append({
            "id": fm["id"],
            "origin": origin,
            "title": fm.get("title", fm["id"]),
            "type": fm.get("type", "result"),
            "status": fm.get("status", "open"),
            "area": fm.get("area", "foundations"),
            "confidence": fm.get("confidence") or None,
            "statement": _no_foreign_url(
                _mark_private(sec.get("Statement", "").strip()), fm["id"], "statement"),
            "verify": _no_foreign_url(
                _mark_private(sec.get("How to verify", "").strip()), fm["id"], "verify") or None,
            "next": _no_foreign_url(
                _mark_private(fm.get("next") or ""), fm["id"], "next") or None,
            "review": review or None,
            "refereed": refereed,
            "awaiting_review": awaiting,
            "verdicts": len(past) or None,
            "review_failed": (verdict.group(1) == "FAILED") if verdict
                             else (bool(past) and past[-1] == "FAILED"),
            "page": page if ("docs/results/" + page) in public else None,
            "related": [r for r in re.split(r",\s*", fm.get("related", "")) if r],
            "evidence": evid,
        })
    if not cards:
        raise Drift("no claims in the knowledge base")

    known = {c["id"] for c in cards}
    byid = {c["id"]: c for c in cards}
    edges, seen = [], set()
    for c in cards:
        for r in c["related"]:
            if r not in known or r == c["id"]:
                continue
            key = tuple(sorted((c["id"], r)))
            if key in seen:
                continue
            seen.add(key)
            edges.append({"a": key[0], "b": key[1],
                          "cross": byid[key[0]]["area"] != byid[key[1]]["area"]})

    by_status = {}
    for c in cards:
        by_status[c["status"]] = by_status.get(c["status"], 0) + 1
    for a in areas:
        a["n"] = sum(1 for c in cards if c["area"] == a["id"])
    orphan = sorted({c["area"] for c in cards} - {a["id"] for a in areas})
    if orphan:
        raise Drift("claims in areas that have no area card: %s" % ", ".join(orphan))

    counts = [
        ("count.cards", len(cards), "cards in the knowledge base, all of them shown"),
        ("count.areas", len(areas), "areas"),
        ("count.never_refereed", never,
         "cards with no referee verdict anywhere in their record: shown, and marked never refereed"),
        ("count.awaiting_review", pending,
         "cards whose review line says pending: awaiting a pass, which is not the same as never "
         "refereed when the history already records one"),
        ("count.review_failed", sum(1 for c in cards if c["review_failed"]),
         "cards whose latest recorded verdict is a failure"),
        ("count.private_pointers", priv,
         "evidence pointers into the private companion: rendered as held privately, never as a link"),
        ("count.private_targets", len(priv_targets),
         "distinct files in the private companion that those pointers name"),
        ("count.public_pointers", pub, "evidence pointers to files git tracks, rendered as links"),
        ("count.kb_pointers", kbp,
         "evidence pointers into the knowledge base itself, which is not published"),
        ("count.missing_pointers", missing,
         "evidence pointers whose target is neither tracked nor on disk"),
        ("count.uncommitted_pointers", uncommitted,
         "evidence pointers to files that exist but neither repository tracks yet"),
        ("count.edges", len(edges), "related-to edges between cards"),
        ("count.with_page", sum(1 for c in cards if c["page"]),
         "cards that also have a generated page under docs/results/"),
        ("count.promoted", sum(1 for c in cards if c["origin"] == "evidence"),
         "cards that started as findings in the knowledge base's evidence folder and reached a "
         "displayed status"),
        ("count.findings_left", findings_left,
         "findings that stay in the knowledge base because they reached no displayed status: they "
         "are audit records, not claims"),
    ]
    records = [record(rid, value, None, "docs/data/extra-claim-map.json", 0, "numerical",
                      label=label,
                      note="counted by tools/build_site_data_extra.py from the knowledge base at "
                           "kb/projects/cft_cmi, which is not published; the line this record "
                           "links to is the count itself.")
               for rid, value, label in counts]
    for rid, value in sorted(by_status.items()):
        records.append(record("count.status." + rid, value, None,
                              "docs/data/extra-claim-map.json", 0, "numerical",
                              label="cards with status %s" % rid,
                              note="counted by tools/build_site_data_extra.py from the knowledge "
                                   "base at kb/projects/cft_cmi, which is not published."))

    payload = {
        "generator": "tools/build_site_data_extra.py",
        "module": "claim-map",
        "note": ("Every card of the private knowledge base kb/projects/cft_cmi, with its status, "
                 "its evidence and the areas as a graph.  A card with no recorded referee verdict "
                 "is marked never refereed rather than hidden, and an evidence pointer whose "
                 "target git does not track is marked held privately rather than linked: the "
                 "public repository and the private companion share one work tree, so presence "
                 "on disk is not publication."),
        "areas": areas,
        "statuses": sorted(by_status),
        "edges": edges,
        "cards": cards,
        "records": records,
    }
    return _resolve_self_lines(payload)


def _resolve_self_lines(payload):
    """The count records above are their own source: point each at the line of
    the file that carries its value.  Writing the line number back cannot move
    any line (one key per line), so one pass is exact."""
    text = json.dumps(payload, indent=1, ensure_ascii=False, sort_keys=False) + "\n"
    lines = text.split("\n")
    for rec in payload["records"]:
        needle = '"id": "%s"' % rec["id"]
        idx = [i for i, ln in enumerate(lines) if ln.strip() == needle + ","
               or ln.strip() == needle]
        if len(idx) != 1:
            raise Drift("cannot locate %s in the emitted JSON" % rec["id"])
        value_line = idx[0] - 5                      # value, error, source, line, status, id
        if not lines[value_line].strip().startswith('"value":'):
            raise Drift("unexpected key order around %s" % rec["id"])
        rec["line"] = value_line + 1
    return payload


