#!/usr/bin/env python3
"""Build docs/data/extra-*.json for modules 7-10 of the interactive site.

Companion to tools/build_site_data.py, which owns docs/data/{constants,
quadratic-law,theta,networks}.json.  This one writes only files whose name
begins with `extra-`, so the two generators never touch each other's output:

    extra-separation.json      module 7, the separation constraint
    extra-off-criticality.json module 8, gap, temperature and mass
    extra-relative-entropy.json module 9, the s2 conjecture and its bracket
    extra-claim-map.json       module 10, the knowledge base as a graph

Every record is

    {"value": <float|null>, "error": <float|null>, "source": "<repo path>",
     "line": <1-based line number>, "status": "<proved|certified|numerical|...>"}

and the page refuses to print a number that has no source.  Nothing is read
from docs/results/*.md: those pages are generated by tools/build_docs.py from
the knowledge base, so sourcing a number there would only echo a copy.

Two rules this file exists to keep:

*   `--check` is byte-exact and exits non-zero on drift.  The output carries no
    timestamp, so a difference means a source file moved under the JSON.
*   every unit, scale factor or column meaning taken from a table is asserted
    to be still declared by that table (`declare` and `header` below).  A
    silently renamed column then fails the build instead of rescaling a number.

Usage
-----
    python3 tools/build_site_data_extra.py            # write docs/data/extra-*.json
    python3 tools/build_site_data_extra.py --check    # re-extract, diff, exit 1 on drift
"""
from __future__ import annotations

import argparse
import json
import math
import re
import subprocess
import unicodedata
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "docs" / "data"
KB = ROOT.parent / "kb" / "projects" / "cft_cmi"

_NUM = r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?"


class Drift(Exception):
    """A source file no longer says what the extractor was told it says."""


# --------------------------------------------------------------------- basics
def read(relpath: str):
    """Return (relpath, [lines]).  Raises if the source has disappeared."""
    p = ROOT / relpath
    if not p.is_file():
        raise Drift("source file missing: %s" % relpath)
    return relpath, p.read_text(encoding="utf-8").splitlines()


def q(x):
    """Round to 12 significant digits: enough for every source read here, and
    it keeps arithmetic on the parsed values free of binary dust."""
    if isinstance(x, float) and math.isfinite(x):
        return float("%.12g" % x)
    if isinstance(x, float):
        return None                      # nan / inf never reach the page
    return x


def record(rid, value, error, source, line, status, **extra):
    r = {"value": q(value), "error": q(error), "source": source,
         "line": line, "status": status, "id": rid}
    r.update({k: v for k, v in extra.items() if v is not None})
    return r


def declare(relpath, lines, needle, why):
    """Assert that the file still declares a unit, scale or convention this
    extractor relies on, and return the line it is declared on.  `needle` is
    matched literally except that any run of whitespace matches any other, so a
    declaration that wraps over two lines still counts."""
    pat = re.compile(r"\s+".join(re.escape(w) for w in needle.split()))
    text = "\n".join(lines)
    m = pat.search(text)
    if m is None:
        raise Drift("%s no longer declares %r (needed for %s)" % (relpath, needle, why))
    return text.count("\n", 0, m.start()) + 1


def header(relpath, lines, pattern, why, start=0):
    """Return the 0-based index of the column header matching `pattern`.
    Reading a column by position is only safe while the header still names it."""
    rx = re.compile(pattern)
    for i in range(start, len(lines)):
        if rx.search(lines[i]):
            return i
    raise Drift("%s: no column header matching %r (needed for %s)"
                % (relpath, pattern, why))


def nums(line):
    """Every number on a line, in order.  'nan' comes back as None."""
    out = []
    for tok in re.findall(r"nan|%s" % _NUM, line):
        out.append(None if tok == "nan" else float(tok))
    return out


def dump(name: str, payload: dict, check: bool) -> bool:
    """Write (or verify) docs/data/<name>.  Returns True when in step."""
    check_payload(name, payload)
    text = json.dumps(payload, indent=1, ensure_ascii=False, sort_keys=False) + "\n"
    path = DATA / name
    if check:
        if not path.is_file():
            print("MISSING  docs/data/%s" % name)
            return False
        if path.read_text(encoding="utf-8") != text:
            print("DRIFTED  docs/data/%s (re-extraction differs from the committed file)" % name)
            return False
        print("ok       docs/data/%s" % name)
        return True
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    print("wrote    docs/data/%s  (%d records)" % (name, len(payload.get("records", []))))
    return True


