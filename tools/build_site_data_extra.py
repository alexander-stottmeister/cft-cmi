def parse_paren(cell: str):
    """'0.0837(5)' -> (0.0837, 0.0005).  The digits in brackets are the
    uncertainty in the last digits of the mantissa."""
    m = re.fullmatch(r"(%s)\((\d+)\)" % _NUM, cell.strip())
    if not m:
        raise Drift("not a value(error) cell: %r" % cell)
    mant, unc = m.group(1), m.group(2)
    dec = len(mant.split(".")[1]) if "." in mant else 0
    return float(mant), int(unc) * 10.0 ** (-dec)


def _one(relpath, lines, pattern, why):
    """The single line matching `pattern`; returns (1-based line, match)."""
    rx, hit = re.compile(pattern), None
    for i, ln in enumerate(lines):
        m = rx.search(ln)
        if m:
            if hit is not None:
                raise Drift("%s: %r matches more than one line (needed for %s)"
                            % (relpath, pattern, why))
            hit = (i + 1, m)
    if hit is None:
        raise Drift("%s: nothing matches %r (needed for %s)" % (relpath, pattern, why))
    return hit


def build_relative_entropy():
    """docs/data/extra-relative-entropy.json.

    s2 = c/12 is a CONJECTURE.  The bracket around it is not simply "proved"
    either: the upper end holds under hypothesis (V), which is open, and the
    lower end rests on Araki's perturbation expansion, whose sources were not
    obtained (Gap RK2).  Both ends are therefore carried as conditional, with
    the hypothesis named on the record."""
    records = []

    src, lines = read("rigor/kubo_mori_gauge_lemma.tex")
    declare(src, lines,
            "The Phase-2b brief proposes the following route to $s_2=c/12$ for an arbitrary "
            "diffeomorphism covariant net.",
            "the document is still the one that brackets s2")

    ln1, m = _one(src, lines, r"\\le\\frac\{11\+5\\sqrt5\}\{24\}\\,c=(%s)\\,c" % _NUM,
                  "the upper end of the bracket")
    records.append(record("bracket.upper", float(m.group(1)), None, src, ln1, "conditional",
                          hypotheses=["(V), uniform integrability along the orbit"],
                          label="limsup s^-2 D <= (11+5 sqrt5)/24 c, Corollary 'what the route proves'",
                          note="(V) is open (Gap RK1); it holds at sigma = 0 only."))

    ln1, m = _one(src, lines, r"\\ge\\frac c\{3\\pi\^2\}=(%s)c" % _NUM,
                  "the lower end of the bracket")
    records.append(record("bracket.lower", float(m.group(1)), None, src, ln1, "conditional",
                          hypotheses=["(H3)", "Araki's perturbation expansion (Gap RK2)"],
                          label="liminf s^-2 D >= (1/2) G(M, phi) >= c/(3 pi^2)",
                          note="Gap RK2: Araki 1973 and Bratteli-Robinson II 5.4.1 were NOT "
                               "OBTAINED, so hypothesis (ii) of the lower-bound theorem is carried "
                               "as a hypothesis rather than checked."))

    ln1, m = _one(src, lines, r"\\frac\{11\+5\\sqrt5\}\{12\}\\,c\\;=\\;(%s)\\,c" % _NUM,
                  "the exact gauge infimum")
    records.append(record("gauge.inf", float(m.group(1)), None, src, ln1, "proved",
                          label="inf over stress-tensor gauges of the Kubo-Mori form = "
                                "(11+5 sqrt5)/12 c, attained in the limit at R* = (3+sqrt5)/2"))

    ln1, m = _one(src, lines, r"\\;=\\;(%s)\\times\\frac c6" % _NUM,
                  "the factor by which the gauge lemma is false")
    records.append(record("gauge.factor", float(m.group(1)), None, src, ln1, "proved",
                          label="the Phase-2b gauge lemma claimed inf = c/6; the true infimum is "
                                "larger by this factor, so the lemma is false"))

    # ---- the fermion measurement and the ladder it is extrapolated from ----
    src, lines = read("fidelity_tables.tex")
    declare(src, lines,
            "\\(s_2\\) from two-point \\(1/\\kappa_c\\) extrapolations",
            "the last row of the table is an extrapolation, not a measurement at finite kappa_c")
    declare(src, lines, "\\label{tab:second-order}", "the table the coefficients are read from")
    h = header(src, lines,
               r"\\\(\\eps\\\) & \\\(\\kappa_c\\\) & \\\(\\Lambda\\\) & \\\(\\kappa_\{\\max\}\\\) & "
               r"\\\(f_2\^\{\\rm sub\}\\\) & \\\(f_2\^\{\\rm sub\}\+\\\)tail & \\\(s_2\^\{\\rm sub\}\\\)",
               "the second-order coefficient table")
    rows = 0
    for i in range(h + 1, len(lines)):
        body = lines[i].strip()
        if body.startswith("\\bottomrule"):
            break
        if body.startswith("\\midrule") or not body:
            continue
        cells = [c.strip() for c in body.replace("\\\\", "").split("&")]
        if len(cells) != 7:
            raise Drift("fidelity_tables.tex:%d: expected 7 cells, got %d" % (i + 1, len(cells)))
        if cells[0].startswith("\\(\\to0"):
            f2, f2e = parse_paren(cells[5])
            s2, s2e = parse_paren(cells[6])
            records.append(record("fermion.f2", f2, f2e, src, i + 1, "numerical",
                                  label="free fermion f2, extrapolated to kappa_c -> infinity"))
            records.append(record("fermion.s2", s2, s2e, src, i + 1, "numerical",
                                  label="free fermion s2, a two-point 1/kappa_c extrapolation from "
                                        "the ladder below, not a measurement at finite kappa_c"))
            rows += 1
            continue
        kc = float(re.sub(r"[^0-9.]", "", cells[1]))
        records.append(record("ladder.s2.%d" % (rows + 1), float(cells[6]), None, src, i + 1,
                              "certified", series="s2_ladder", x=kc,
                              label="s2 restricted to the spectral window, kappa_c = %s "
                                    "(a rigorous lower bound, Lambda = %s)" % (kc, cells[2])))
        rows += 1
    if rows != 10:
        raise Drift("fidelity_tables.tex: expected 9 window rows and one extrapolation, read %d" % rows)

    # ---- the bosonic check ------------------------------------------------
    src, lines = read("rigor/findings.tex")
    ln1, m = _one(src, lines,
                  r"U\(1\) current net.*?f_2=(%s)\((\d+)\).*?s_2=(%s)\((\d+)\)" % (_NUM, _NUM),
                  "the bosonic check")
    f2b, f2be = parse_paren("%s(%s)" % (m.group(1), m.group(2)))
    s2b, s2be = parse_paren("%s(%s)" % (m.group(3), m.group(4)))
    records.append(record("boson.f2", f2b, f2be, src, ln1, "numerical",
                          label="U(1) current net, Gaussian mode compression in the modular frame "
                                "(numerics/boson)"))
    records.append(record("boson.s2", s2b, s2be, src, ln1, "numerical",
                          label="U(1) current net s2, the second independent net at c = 1"))

    # ---- the conjectured value itself -------------------------------------
    src, lines = read("rigor/check_note5_numerics.tex")
    ln1, m = _one(src, lines, r"s_2=1/12=(%s)" % _NUM, "the conjectured value of s2")
    records.append(record("conj.s2", float(m.group(1)), None, src, ln1, "conjectural",
                          label="s2 = c/12 at c = 1: believed, and consistent with both "
                                "measurements, but not proved for any net"))
    ln1, m = _one(src, lines, r"f_2=1/\(12\\pi\^2\)=(%s)" % _NUM, "f2 for the comparison")
    records.append(record("thm.f2", float(m.group(1)), None, src, ln1, "proved",
                          label="f2 = c/(12 pi^2) at c = 1, Theorem A: the coefficient that IS proved"))

    return {
        "generator": "tools/build_site_data_extra.py",
        "module": "relative-entropy",
        "note": ("s2 = c/12 is a conjecture.  The two ends of the bracket are conditional, not "
                 "proved: the upper end needs (V) (open), the lower end needs Araki's perturbation "
                 "expansion, whose sources were not obtained (Gap RK2 of "
                 "rigor/kubo_mori_gauge_lemma.tex).  The two measurements are at c = 1."),
        "records": records,
    }


